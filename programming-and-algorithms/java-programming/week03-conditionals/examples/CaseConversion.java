import java.util.Scanner;

/**
 * [3-2 조건문2] [실습] 문자 변환 (소문자 → 대문자, 대문자 → 소문자)
 *
 * - 문자는 내부적으로 2Byte 숫자(유니코드)로 표현된다.
 * - 그래서 코드값을 비교하여 대/소문자를 판별할 수 있다.  (c >= 'a' && c <= 'z')
 *
 * 📝 필기 (실습 조건문1 3번에서 정리)
 *  - 아스키코드상 A 는 65, ..... , Z 는 90, [ 는 91, .... , a 는 97, ..... , z 는 122.
 *  - char 타입은 내부적으로 아스키 코드(int) 값으로 저장된다.
 *    따라서 두 문자를 빼서 연산하면 알파벳 순서상 떨어져 있는 "거리(알파벳 위치 차이)" 를 구할 수 있다.
 *  - 문자들 간의 거리는 어떻게 구할까?  x = 'B' 라고 하면
 *    x - 'A' 를 하면 실제로는 66 - 65 라서 1 이 나온다.
 *      'B' - 'A' → 66 - 65 = 1   (A 로부터 1번째 뒤에 위치)
 *      'Z' - 'A' → 90 - 65 = 25  (A 로부터 25번째 뒤에 위치)
 *  - 대문자 → 소문자 : 'a' + (x - 'A')
 *      1. x - 'A'   → 'B' - 'A' = 1  (거리 계산)
 *      2. 'a' + 1   → 97 + 1    = 98
 *      3. (char) 98 → 'b'
 *  - 소문자 → 대문자는 반대로 'A' + (x - 'a')  (아래 코드의 c - 'a' + 'A' 와 같다)
 *
 * 💡 char - char, char + int 의 결과는 int 이다. (연산 시 int 로 자동 형변환)
 *    그래서 다시 char 변수에 넣으려면 (char) 로 강제 형변환해야 한다.
 * 💡 대문자와 소문자는 항상 32 차이 ('a' - 'A' = 97 - 65 = 32).
 *    c + 32 로도 되지만 'a' - 'A' 처럼 의미가 보이게 쓰는 편이 읽기 좋다.
 *
 * 실행 예
 *  영문자를 입력하세요 :
 *  B
 *  변환 결과 : b
 */
public class CaseConversion {
    public static void main(String[] args) {
        Scanner sc = new Scanner(System.in);
        System.out.println("영문자를 입력하세요 : ");
        char c = sc.next().charAt(0);
        sc.close();

        if (c >= 'a' && c <= 'z') c = (char) (c - 'a' + 'A');        // 소문자 → 대문자
        else if (c >= 'A' && c <= 'Z') c = (char) (c - 'A' + 'a');   // 대문자 → 소문자
        else {
            System.out.println("영문자가 아닙니다.");
            return;
        }
        System.out.println("변환 결과 : " + c);
    }
}
