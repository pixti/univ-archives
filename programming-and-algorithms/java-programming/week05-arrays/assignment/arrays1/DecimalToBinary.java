import java.util.Scanner;

/**
 * [5강 과제] 배열(1) - 3번 문제
 *
 * 10 진수를 입력받아 2 진수로 변환하여 출력하는 프로그램을 작성하시오.
 *  - 최대 64 자리까지 표현하고, 2 진수의 각 자리는 배열에 저장한다.
 *  - 처음 1 이 나오기 전의 0 은 출력하지 않는다.
 *    (예) 9  → 000...001001 이 아니라 1001
 *         15 → 000...001111 이 아니라 1111
 *
 * 📝 필기 (AI 설명) : 왜 배열에 역순으로 저장되는가?
 *   16 을 2 로 계속 나누면
 *     16 / 2 → 몫 8, 나머지 0
 *      8 / 2 → 몫 4, 나머지 0
 *      4 / 2 → 몫 2, 나머지 0
 *      2 / 2 → 몫 1, 나머지 0
 *      1 / 2 → 몫 0, 나머지 1
 *   나머지는 0 0 0 0 1 순서로 나오지만, 2 진수는 거꾸로 읽어야 하므로 1 0 0 0 0 이 된다.
 *   그래서 binary[0] = 0, binary[1] = 0, binary[2] = 0, binary[3] = 0, binary[4] = 1 로 저장된다.
 *   → 낮은 자리부터 저장되므로, 출력할 때 뒤에서부터 읽는다.
 *
 * 📝 필기 (AI 설명) : index 가 필요한 이유
 *   배열은 64 칸이지만 모두 사용하는 것이 아니다. 예를 들어 9 는
 *     binary[0] = 1, binary[1] = 0, binary[2] = 0, binary[3] = 1
 *   로 0 ~ 3 까지만 데이터가 들어간다. index 는 마지막으로 저장한 다음 위치를 기억하고,
 *   반복이 끝나면 index 는 4 가 된다.
 *     for (int i = index - 1; i >= 0; i--)
 *   이므로 3 → 2 → 1 → 0 순서로 출력된다.
 *   → 사용한 칸까지만 출력하므로 "처음 1 이 나오기 전의 0" 은 자연스럽게 출력되지 않는다.
 *
 * 포인트
 *  - long : int(약 21 억, 31 비트)보다 큰 수도 받으려고. 최대 64 자리 조건에 맞춘 것.
 *  - (int)(num % 2) : long 끼리 연산한 결과는 long 이라서 int 배열에 넣으려면 형변환이 필요.
 *  - 5-1 강의 "값 배열에 읽어들이기" 의 idx 와 같은 역할 : 다음에 넣을 위치 = 지금까지 넣은 개수.
 *
 * ⚠ 0 을 입력하면 while 을 한 번도 돌지 않아 아무것도 출력되지 않는다. (0 의 2 진수는 0)
 * ⚠ 음수도 while (num > 0) 를 통과하지 못해 아무것도 출력되지 않는다.
 *   → 리팩터링 버전에서 둘 다 처리했다.
 * 💡 long 의 양수 최대값은 2^63 - 1 이라 실제로는 63 자리까지 나온다. (64 칸이면 충분)
 * 💡 검산 : Long.toBinaryString(142924) 도 100010111001001100
 *
 * 실행 예
 *  10진수를 입력하세요. : 142924
 *  100010111001001100
 */
public class DecimalToBinary {
    public static void main(String[] args) {
        Scanner sc = new Scanner(System.in);
        long num;
        int[] binary = new int[64];
        int index = 0;

        System.out.print("10진수를 입력하세요. : ");
        num = sc.nextLong();

        // 10진수를 2진수로 변환
        while (num > 0) {
            binary[index] = (int) (num % 2);
            num = num / 2;
            index++;
        }

        // 역순으로 출력
        for (int i = index - 1; i >= 0; i--) {
            System.out.print(binary[i]);
        }
        sc.close();
    }
}
