/**
 * [5강 과제] 배열(2) - 2번 문제
 *
 * 다음 표를 2 차원 배열에 저장한 뒤, 각 행의 합계와 각 열의 합계를 출력하는 프로그램을 작성하시오.
 *
 *     12  56  32  16  98
 *     99  56  34  41   3
 *     65   3  87  78  21
 *
 * 포인트
 *  - 행 합계 : 바깥 for = 행, 안쪽 for = 열.  행이 바뀔 때마다 sum = 0 으로 다시 시작.
 *  - 열 합계 : 바깥 for = 열, 안쪽 for = 행.  두 for 의 순서만 바꾸면 된다.
 *  - arr.length       = 행의 수 (3)
 *    arr[row].length  = row 번째 행의 열 수 (5)
 *    arr[0].length    = 열 합계에서 "열의 수" 로 사용 (모든 행의 길이가 같다고 가정)
 *  - sum = 0 위치가 핵심. 바깥 for 안, 안쪽 for 바로 앞에 둬야 행(열)마다 따로 더해진다.
 *    for 밖에 두면 누적 합이 되어 2 번째 행부터 값이 틀린다.
 *
 *         열 →   0   1   2   3   4  | 행 합계
 *     행 0      12  56  32  16  98  |  214
 *     행 1      99  56  34  41   3  |  233
 *     행 2      65   3  87  78  21  |  254
 *     ───────────────────────────────
 *     열 합계  176 115 153 135 122
 *
 * 💡 arr[0].length 는 모든 행의 길이가 같을 때만 맞다. 행마다 길이가 다른 배열(5-3 강의 비정방형 배열)이면
 *    리팩터링 버전처럼 가장 긴 행의 길이를 구하고, 짧은 행은 건너뛰어야 한다.
 *
 * 실행 예
 *  1번째 행의 합계 : 214
 *  2번째 행의 합계 : 233
 *  3번째 행의 합계 : 254
 *  1번째 열의 합계 : 176
 *  2번째 열의 합계 : 115
 *  3번째 열의 합계 : 153
 *  4번째 열의 합계 : 135
 *  5번째 열의 합계 : 122
 */
public class RowColumnSum {
    public static void main(String[] args) {
        int[][] arr = {
                {12, 56, 32, 16, 98},
                {99, 56, 34, 41, 3},
                {65, 3, 87, 78, 21}
        };
        int row, col;
        int sum;

        // 각 행의 합계
        for (row = 0; row < arr.length; row++) {
            sum = 0;
            for (col = 0; col < arr[row].length; col++) {
                sum = sum + arr[row][col];
            }
            System.out.println((row + 1) + "번째 행의 합계 : " + sum);
        }

        // 각 열의 합계
        for (col = 0; col < arr[0].length; col++) {
            sum = 0;
            for (row = 0; row < arr.length; row++) {
                sum = sum + arr[row][col];
            }
            System.out.println((col + 1) + "번째 열의 합계 : " + sum);
        }
    }
}
