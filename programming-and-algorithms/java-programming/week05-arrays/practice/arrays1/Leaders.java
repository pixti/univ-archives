/**
 * [5강 실습] 배열(1) - 8번 문제
 *
 * 배열에서 모든 리더를 찾아 출력하는 프로그램을 작성하시오.
 * 리더 : 오른쪽에 있는 모든 요소보다 큰 요소. (가장 오른쪽 요소는 항상 리더)
 *   배열 : [10, 9, 14, 23, 15, 0, 9]
 *
 *   (예시 출력)
 *   리더들 : 23 15 9
 *
 * 포인트
 *  - 바깥 for (i) : 리더 후보 하나씩
 *  - 안쪽 for (j = i + 1 ~) : i 의 오른쪽에 i 번째보다 큰 값이 있는지 검사
 *      있으면 i 번째는 리더가 아니다 → break
 *  - j == my_arr.length : break 없이 끝까지 검사했다 = 더 큰 값이 없었다 → 리더
 *    (1번 문제의 i == my_array.length, 4-4 소수 판별의 i == n 과 같은 발상)
 *  - 마지막 원소는 j = i + 1 = length 라서 안쪽 for 를 한 번도 돌지 않고 바로 리더가 된다.
 *  - i, j 를 for 밖에서 선언한 이유 : 반복이 끝난 뒤 j 값을 써야 해서.
 *
 *     i=0  10 : 오른쪽에 14 → 아님
 *     i=1   9 : 오른쪽에 14 → 아님
 *     i=2  14 : 오른쪽에 23 → 아님
 *     i=3  23 : 15, 0, 9 모두 작음 → 리더
 *     i=4  15 : 0, 9 모두 작음 → 리더
 *     i=5   0 : 오른쪽에 9 → 아님
 *     i=6   9 : 오른쪽 없음 → 리더
 *
 * 💡 비교가 my_arr[i] < my_arr[j] (엄격) 라서, 오른쪽에 "같은" 값만 있으면 리더로 판정된다.
 *    "모든 요소보다 크다" 를 엄격하게 적용하려면 <= 로 바꿔야 한다. 이 예제에서는 결과가 같다.
 * 💡 오른쪽부터 거꾸로 훑으면서 "지금까지의 최대값" 보다 크면 리더로 판단하면 한 번만 훑어도 된다.
 *    대신 출력 순서가 9 15 23 으로 거꾸로 나온다.
 *
 * 실행 예
 *  리더들 : 23 15 9
 */
public class Leaders {
    public static void main(String[] args) {
        int[] my_arr = new int[] {10, 9, 14, 23, 15, 0, 9};
        int i, j;

        System.out.print("리더들 : ");
        for (i = 0; i < my_arr.length; i++) {
            // i번째 값이 리더인지 검사, i번째 값보다 큰 값이 있는지 검사
            for (j = i + 1; j < my_arr.length; j++) {
                if (my_arr[i] < my_arr[j]) {   // i번째 값이 리더가 아님
                    break;
                }
            }
            // 끝까지 검사했다면 i번째 값은 리더임.
            if (j == my_arr.length) {
                System.out.print(my_arr[i] + " ");
            }
        }
        System.out.println();
    }
}
