/**
 * [4-3 반복문3] for 문 - 파이썬 for 문을 자바 for 문으로 / 증감식의 여러 형태
 *
 * for 문
 *  - while 문과 함께 널리 쓰이는 반복문. 반복 횟수가 정해져 있을 때 주로 사용.
 *  - 초기식 : 반복문이 실행되기 전에 초기화해야 할 내용. 반복문이 실행되기 전 딱 한 번 실행.
 *  - 조건을 만족하면 반복 내용을 실행 후 증감식을 실행.
 *
 *    for (초기식; 반복 조건; 증감식) {        (Python)  for 반복변수 in 시퀀스 :
 *        반복 내용                                         반복문장들
 *    }
 *
 *    실행 순서 : ① 초기식(한 번) → ② 조건 검사 → ③ 반복 내용 → ④ 증감식 → ②로 ...
 *
 * 파이썬으로 작성한 for 문
 *    sum = 0
 *    for i in range(10, 0, -1):
 *        sum += i
 *    print("합 : " + str(sum))
 *
 * 슬라이드 옆에 적힌 형태 : for (int sum = 0, i = 10; i > 0; i--)
 *  💡 이렇게 sum 을 초기식에서 선언하면 sum 도 for 안에서만 쓰는 지역 변수가 되어
 *     for 가 끝난 뒤 println("합 : " + sum) 을 쓰면 에러. → 결과를 밖에서 쓰려면 for 앞에서 선언.
 *  💡 초기식에는 쉼표로 "같은 자료형 변수 여러 개 선언" 또는 "식 여러 개" 를 쓸 수 있다.
 *     하지만 선언과 식을 섞을 수는 없다. (실습 반복문2-1번 참고)
 *
 * 증감식의 여러 형태 (Python range 와 비교)
 *    for (i = 1; i <= 10; i++)        ↔ range(1, 11)       1, 2, ..., 10   하나씩 증가
 *    for (i = 10; i >= 1; i--)        ↔ range(10, 0, -1)   10, 9, ..., 1   하나씩 감소
 *    for (i = 1; i < 10; i = i + 3)   ↔ range(1, 11, 3)    세개씩 증가
 *  ⚠ 세 번째 짝은 정확히 같지 않다. 자바 i < 10 은 1, 4, 7 (10 제외),
 *    파이썬 range(1, 11, 3) 은 1, 4, 7, 10. 같게 하려면 i <= 10 으로 써야 한다.
 *
 * 실행 예
 *  합 : 55
 *  하나씩 증가 : 55
 *  하나씩 감소 : 55
 *  세개씩 증가 : 12
 */
public class ForSum {
    public static void main(String[] args) {
        int sum = 0;
        for (int i = 10; i > 0; i--) {  // 한줄인 경우 중괄호 생략 가능
            sum += i;
        }
        System.out.println("합 : " + sum);

        // ===== 증감식의 여러 형태 =====
        int i;

        sum = 0;
        for (i = 1; i <= 10; i++) {         // 하나씩 증가
            sum = sum + i;
        }
        System.out.println("하나씩 증가 : " + sum);

        sum = 0;
        for (i = 10; i >= 1; i--) {         // 하나씩 감소
            sum = sum + i;
        }
        System.out.println("하나씩 감소 : " + sum);

        sum = 0;
        for (i = 1; i < 10; i = i + 3) {    // 세개씩 증가 (1 + 4 + 7)
            sum = sum + i;
        }
        System.out.println("세개씩 증가 : " + sum);
    }
}
