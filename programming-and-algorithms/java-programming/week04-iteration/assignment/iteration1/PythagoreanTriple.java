/**
 * [4강 과제] 반복문1 - 2번 문제
 * ※ 반복 시 while 이나 do while 문만 사용하시오.
 *
 * 피타고라스의 정리는 직각 삼각형에서 직각을 낀 두 변의 길이를 a, b 라고 하고, 빗변의 길이를 c 라고 하면
 * a^2 + b^2 = c^2 의 수식이 성립한다는 것이다. 각 변의 길이가 100 보다 작은 삼각형 중에서
 * 피타고라스 정리가 성립하는 직각 삼각형은 몇 개나 있을까? 3 중 반복문을 이용하여
 * 피타고라스 정리를 만족하는 3 개의 정수 각각을 출력하도록 한다.
 *
 * 📝 필기 (코드 주석)
 *  - while (c <= 100) {  // c가 1~100 까지 반복
 *  - while (a < c) {     // a가 1~c-1까지 반복
 *  - while (b < c) {     // b가 1~c-1까지 반복
 *
 * 포인트
 *  - 빗변 c 가 가장 긴 변이므로 a, b 는 c 보다 작은 값만 보면 된다. (a < c, b < c)
 *  - while 로 3 중 반복을 만들 때는 안쪽 변수를 바깥 반복 안에서 다시 1 로 초기화해야 한다.
 *      a = 1;  ← c 가 바뀔 때마다     b = 1;  ← a 가 바뀔 때마다
 *    (빼먹으면 두 번째 c 부터 안쪽 반복이 돌지 않는다. 실습 Pyramid 의 col = 0; 과 같은 이야기)
 *  - 제곱은 a * a 로 계산. (Math.pow 는 double 을 돌려줘서 == 비교에 부적합)
 *
 * 💡 (a, b) 와 (b, a) 를 모두 센다. 예 : 5 : 3 : 4 와 5 : 4 : 3 → 그래서 총 104 개.
 *    순서를 무시한 서로 다른 삼각형은 52 개. (리팩터링 버전 PythagoreanTripleRefactored 참고)
 *    문제의 출력 예도 104 개라 이 방식이 의도된 답.
 * 💡 문제는 "100 보다 작은" 이지만 출력 예에 100 : 28 : 96 이 있으므로 c <= 100 으로 맞췄다.
 * 💡 반복 횟수 : c 마다 (c-1)² 번 → 약 100 × 100 × 100 / 3 ≈ 33 만 번. 컴퓨터에게는 순식간.
 *
 * 문제의 실행 예 (끝부분)
 *  85 : 36 : 77
 *  ...
 *  100 : 96 : 28
 *  총 104개
 *
 * 내 코드 실행 예 (끝부분)
 *  91 : 84 : 35
 *  95 : 57 : 76
 *  95 : 76 : 57
 *  97 : 65 : 72
 *  97 : 72 : 65
 *  100 : 28 : 96
 *  100 : 60 : 80
 *  100 : 80 : 60
 *  100 : 96 : 28
 *  총 104개
 */
public class PythagoreanTriple {
    public static void main(String[] args) {

        int a, b, c = 1, count = 0;
        while (c <= 100) {          // c가 1~100 까지 반복
            a = 1;
            while (a < c) {         // a가 1~c-1까지 반복
                b = 1;
                while (b < c) {     // b가 1~c-1까지 반복
                    if (a * a + b * b == c * c) { System.out.println(c + " : " + a + " : " + b); count++; }
                    b++;
                }
                a++;
            }
            c++;
        }
        System.out.println("총 " + count + "개");
    }
}
