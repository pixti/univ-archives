/**
 * [4강 과제] 반복문2 - 2번 문제
 * 📝 반복문2 과제는 for문으로 작성.
 *
 * 피타고라스의 정리는 직각 삼각형에서 직각을 낀 두 변의 길이를 a, b 라고 하고, 빗변의 길이를 c 라고 하면
 * a^2 + b^2 = c^2 의 수식이 성립한다는 것이다. 각 변의 길이가 100 보다 작은 삼각형 중에서
 * 피타고라스 정리가 성립하는 직각 삼각형은 몇 개나 있을까? 3 중 반복문을 이용하여
 * 피타고라스 정리를 만족하는 3 개의 정수 각각을 출력하도록 한다.
 *
 * 📝 필기 (코드 주석)
 *  - for (c = 1; c <= 100; c++) {  // c가 1~100까지 반복
 *  - for (a = 1; a < c; a++) {     // a가 1~c-1까지 반복
 *  - for (b = 1; b < c; b++) {     // b가 1~c-1까지 반복
 *
 * 포인트
 *  - 반복문1(iteration1/PythagoreanTriple.java) 의 while 3 중 반복을 for 로 옮긴 것.
 *  - for 는 초기식(a = 1, b = 1) 이 반복문 머리에 있어서
 *    "안쪽 변수를 매번 다시 초기화" 하는 것을 빼먹을 수가 없다.
 *    (while 버전에서는 a = 1; b = 1; 을 직접 적어야 했다)
 *  - a, b, c 를 for 바깥에서 선언했다. for (int c = 1; ...) 처럼 초기식에서 선언해도 된다.
 *
 * 💡 (a, b) 와 (b, a) 를 모두 세므로 총 104 개. (문제의 출력 예와 같다)
 * 💡 문제는 "100 보다 작은" 이지만 출력 예에 100 : 28 : 96 이 있으므로 c <= 100 으로 맞췄다.
 *
 * 내 코드 실행 예 (끝부분)
 *  97 : 65 : 72
 *  97 : 72 : 65
 *  100 : 28 : 96
 *  100 : 60 : 80
 *  100 : 80 : 60
 *  100 : 96 : 28
 *  총 104개
 */
public class PythagoreanTripleFor {
    public static void main(String[] args) {

        int a, b, c, count = 0;
        for (c = 1; c <= 100; c++) {            // c가 1~100까지 반복
            for (a = 1; a < c; a++) {           // a가 1~c-1까지 반복
                for (b = 1; b < c; b++) {       // b가 1~c-1까지 반복
                    if (a * a + b * b == c * c) {
                        System.out.println(c + " : " + a + " : " + b);
                        count++;
                    }
                }
            }
        }
        System.out.println("총 " + count + "개");
    }
}
