/**
 * [2강 퀴즈] 수식 연습문제 (1 ~ 5번)
 *
 * ──────────────────────────────────────────────────────────────
 * 참고 자료: 자바 연산자 우선순위 (위쪽일수록 먼저 계산)
 * ──────────────────────────────────────────────────────────────
 * | 순위 | 연산자                                         | 내용                  |
 * |------|------------------------------------------------|-----------------------|
 * | 1    | () []                                          | 괄호 / 대괄호          |
 * | 2    | ! ~ ++ --                                      | 부정 / 증감 연산자      |
 * | 3    | * / %                                          | 곱셈 / 나눗셈 연산자    |
 * | 4    | + -                                            | 덧셈 / 뺄셈 연산자      |
 * | 5    | << >> >>>                                      | 비트 단위 시프트 연산자 |
 * | 6    | < <= > >=                                      | 관계 연산자            |
 * | 7    | == !=                                          |                       |
 * | 8    | &                                              | 비트 단위 논리 연산자   |
 * | 9    | ^                                              |                       |
 * | 10   | |                                              |                       |
 * | 11   | &&                                             | 논리곱 연산자          |
 * | 12   | ||                                             | 논리합 연산자          |
 * | 13   | ? :                                            | 조건 연산자            |
 * | 14   | = += -= *= /= %= <<= >>= >>>= &= ^= |=         | 대입 / 할당 연산자      |
 *
 * 결합 순위 (우선순위가 같을 때의 연산 방향)
 *  - 단항 연산자 (++ -- + - ~ ! (타입))     : 오른쪽 → 왼쪽  ←
 *  - 산술 / 시프트 / 비교 / 논리 / 삼항     : 왼쪽 → 오른쪽  →
 *  - 대입 연산자 (= *= /= %= += -= ...)      : 오른쪽 → 왼쪽  ←
 *
 * ⚠ 위 결합 순위 표(퀴즈 참고 자료)에는 삼항 연산자가 "→" 로 되어 있지만,
 *   강의 슬라이드(2-5) 설명처럼 삼항 연산자는 실제로 오른쪽 → 왼쪽으로 결합한다.
 *   예) a ? b : c ? d : e  ==  a ? b : (c ? d : e)
 */
public class ExpressionQuiz {
    public static void main(String[] args) {
        q1();
        q2();
        q3();
        q4();
        q5();
    }

    /**
     * 1. int x = 5, y = 3, z = 2; 일 때 각 변수에는 어떤 값이 저장되는가? (각 문항은 독립적으로 계산)
     *
     *  ① x += y -= 2;
     *     - 대입 연산자는 오른쪽에서 왼쪽으로 처리된다.
     *     - 먼저 y -= 2 가 실행되어 y 는 1 (3 - 2 = 1)
     *     - 그 후 x += 1 이 되어 x 는 6 (5 + 1 = 6)
     *     → 결과: x = 6, y = 1, z = 2
     *
     *  ② x *= y + 2;
     *     - 산술 연산자(+)가 복합 대입 연산자(*=)보다 우선순위가 높다.
     *     - 먼저 y + 2 가 계산되어 5 (3 + 2 = 5)
     *     - 그 후 x *= 5 가 되어 x 는 25 (5 * 5 = 25)
     *     → 결과: x = 25, y = 3, z = 2
     *
     *  ③ z = ++x + ++y;
     *     - 전위 증가 연산자(++변수)는 값을 먼저 1 증가시킨 후 연산에 사용한다.
     *     - ++x 가 실행되어 x 는 6, ++y 가 실행되어 y 는 4
     *     - z = 6 + 4 가 계산되어 z 는 10
     *     → 결과: x = 6, y = 4, z = 10
     *
     *  ④ z = x++ + ++y;
     *     - 후위 증가 연산자(변수++)는 현재 값을 먼저 연산에 사용한 후 나중에 1 증가시킨다.
     *       따라서 수식에는 x 의 기존 값 5 가 사용되고, 그 직후에 x 는 6 으로 증가.
     *     - 전위 증가 연산자(++y)는 먼저 1 증가시키므로 y 는 4 가 되고 수식에도 4 가 사용.
     *     - z = 5 + 4 가 계산되어 z 는 9
     *     → 결과: x = 6, y = 4, z = 9
     *
     * 📝 필기 (질문: 전위증가연산자는 y 다음 x 순서가 아니라 x 다음 y 임?)
     *  - x 가 먼저 처리되고 그다음 y 가 처리되는 것이 맞다.
     *  - 자바는 수식을 계산할 때 "피연산자(항)를 무조건 왼쪽에서 오른쪽(Left-to-Right) 순서로 평가"한다는
     *    엄격한 규칙이 있다. 연산자 우선순위와는 별개로, 수식 안의 변수나 값을 읽어오는 기본 방향 자체가 왼쪽부터.
     *  - z = ++x + ++y; 의 정확한 내부 실행 순서
     *    1단계 (왼쪽 항 평가)  : + 를 기준으로 왼쪽 항 ++x 를 먼저 실행 → x 가 5 → 6 (왼쪽은 6 으로 확정)
     *    2단계 (오른쪽 항 평가): 다음으로 오른쪽 항 ++y 를 실행 → y 가 3 → 4 (오른쪽은 4 로 확정)
     *    3단계 (덧셈 연산)     : 양쪽 값이 모두 준비되었으므로 6 + 4 = 10
     *    4단계 (대입 연산)     : 우선순위가 가장 낮은 대입 연산자(=)가 마지막에 실행되어 z 에 10 저장
     *  - 참고: C/C++ 같은 일부 언어는 컴파일러 최적화 방식에 따라 오른쪽 항을 먼저 계산하기도 하지만,
     *          자바는 어떤 컴퓨터에서 실행하든 결과가 똑같도록 '왼쪽부터 순서대로 처리'를 언어 스펙으로 강제한다.
     */
    static void q1() {
        int x, y, z;

        x = 5; y = 3; z = 2;
        x += y -= 2;
        System.out.println("[Q1-①] x=" + x + ", y=" + y + ", z=" + z); // x=6, y=1, z=2

        x = 5; y = 3; z = 2;
        x *= y + 2;
        System.out.println("[Q1-②] x=" + x + ", y=" + y + ", z=" + z); // x=25, y=3, z=2

        x = 5; y = 3; z = 2;
        z = ++x + ++y;
        System.out.println("[Q1-③] x=" + x + ", y=" + y + ", z=" + z); // x=6, y=4, z=10

        x = 5; y = 3; z = 2;
        z = x++ + ++y;
        System.out.println("[Q1-④] x=" + x + ", y=" + y + ", z=" + z); // x=6, y=4, z=9
    }

    /**
     * 2. 다음 논리 연산을 설명해 보아라.
     *
     *  ① (x >= 10) || (x < 30)
     *     - 의미: x 가 10 이상이거나(OR), x 가 30 미만일 때 참.
     *     - 참고: 모든 숫자는 "10 이상" 또는 "30 미만" 중 하나는 무조건 만족하므로,
     *             x 에 어떤 값이 들어가도 항상 참(true)이 되는 식.
     *
     *  ② !(x == 20) && !(x == 30)
     *     - 의미: x 가 20 이 아니고(AND), 동시에 x 가 30 도 아닐 때 참.
     *     - 참고: 부정 연산자(!)를 안으로 넣어 (x != 20) && (x != 30) 으로 써도 완전히 동일.
     *
     *  ③ (x == 30) || !(x > 20)
     *     - 의미: x 가 30 이거나(OR), x 가 20 보다 크지 않을 때 참.
     *     - 참고: "20 보다 크지 않다" = "20 이하" 이므로 (x == 30) || (x <= 20) 으로 바꿔 써도 같다.
     */
    static void q2() {
        int[] samples = {5, 20, 25, 30, 40};
        for (int x : samples) {
            boolean r1 = (x >= 10) || (x < 30);
            boolean r2 = !(x == 20) && !(x == 30);
            boolean r3 = (x == 30) || !(x > 20);
            System.out.println("[Q2] x=" + x + " → ① " + r1 + ", ② " + r2 + ", ③ " + r3);
        }
    }

    /**
     * 3. 다음 수식에서 연산자 밑에 계산 순서를 숫자로 적어 보아라.
     *
     *  ① x = y + z + 10
     *        3   1   2
     *     - 계산 순서: 1. + (왼쪽) → 2. + (오른쪽) → 3. =
     *     - 덧셈(+)이 대입(=)보다 우선순위가 높다. 같은 + 끼리는 왼쪽에서 오른쪽으로 결합.
     *
     *  ② x % y / z * w
     *       1   2   3
     *     - 계산 순서: 1. % → 2. / → 3. *
     *     - %, /, * 는 모두 우선순위가 같으므로 기본 규칙대로 왼쪽에서 오른쪽 순서.
     *
     *  ③ x = y = z % w
     *       3   2   1
     *     - 계산 순서: 1. % → 2. = (오른쪽) → 3. = (왼쪽)
     *     - 나머지(%)가 가장 먼저. 대입 연산자(=)가 여러 개일 때는
     *       다른 연산자와 달리 오른쪽에서 왼쪽 방향으로 결합하여 값을 할당한다.
     */
    static void q3() {
        int x, y = 7, z = 3, w = 4;
        x = y + z + 10;
        System.out.println("[Q3-①] " + x + " == ((7 + 3) + 10) = " + ((7 + 3) + 10));

        x = 17;
        int r = x % y / z * w;
        System.out.println("[Q3-②] " + r + " == ((17 % 7) / 3) * 4 = " + (((17 % 7) / 3) * 4));

        x = y = z % w;
        System.out.println("[Q3-③] x=" + x + ", y=" + y + " (z % w = " + (z % w) + ")");
    }

    /**
     * 4. 다음 문장에 해당하는 조건식을 써 보아라.
     *  ① x 는 짝수이다.                → x % 2 == 0
     *  ② x 는 5 의 배수이다.            → x % 5 == 0
     *  ③ x 는 3 과 같거나 7 이하이다.    → x == 3 || x <= 7
     *     (참고: 논리적으로는 x <= 7 만 써도 3 인 경우를 포함하지만, 문장을 그대로 직역하면 위와 같다.)
     *  ④ x 가 0 이상이고 100 이하이다.   → x >= 0 && x <= 100
     *     (참고: 프로그래밍에서는 0 <= x <= 100 처럼 한 번에 쓸 수 없으므로 && 로 묶어야 한다.
     *            자바에서 0 <= x <= 100 은 (0 <= x) 가 boolean 이 되어 boolean <= int 비교 → 컴파일 에러)
     *  ⑤ x 가 1 도 아니고 100 도 아니다. → x != 1 && x != 100
     */
    static void q4() {
        int x = 10;
        System.out.println("[Q4] x=" + x
                + " | ① " + (x % 2 == 0)
                + " | ② " + (x % 5 == 0)
                + " | ③ " + (x == 3 || x <= 7)
                + " | ④ " + (x >= 0 && x <= 100)
                + " | ⑤ " + (x != 1 && x != 100));
    }

    /**
     * 5. 다음 조건에 해당하는 논리 연산식을 만들어 보자.
     *  ① 무주택 기간(year) 3년 이상, 가구주의 연령(age)이 40세 이상, 가족의 수(count)가 3명 이상
     *     → year >= 3 && age >= 40 && count >= 3
     *  ② 나이(age) 6세 이하, 키(height)는 150cm 이상
     *     → age <= 6 && height >= 150
     *  ③ 4의 배수이면서 100의 배수가 아닌 연도(year). 단 400의 배수는 포함
     *     → (year % 4 == 0 && year % 100 != 0) || (year % 400 == 0)
     *     참고: 프로그래밍에서 윤년을 판별할 때 사용하는 대표적인 표준 논리식.
     *  ④ 평균 학점(ave) 3.0 이상이고, 토플 점수(toefl) 300점 이상이거나 700점 이하
     *     → ave >= 3.0 && (toefl >= 300 || toefl <= 700)
     *     참고: 문장("300점 이상이거나 700점 이하")을 그대로 직역한 결과.
     *           다만 이 조건은 모든 점수를 포함하게 되므로, 출제 의도가 "300점 이상이면서 700점 이하" 였다면
     *           괄호 안을 (toefl >= 300 && toefl <= 700) 으로 쓰는 것이 자연스럽다.
     *     ⚠ && 가 || 보다 우선순위가 높으므로 괄호를 빼면 (ave >= 3.0 && toefl >= 300) || toefl <= 700 이 되어
     *       의미가 달라진다. 괄호 필수!
     */
    static void q5() {
        int year = 5, age = 45, count = 4;
        System.out.println("[Q5-①] " + (year >= 3 && age >= 40 && count >= 3));

        int age2 = 5, height = 152;
        System.out.println("[Q5-②] " + (age2 <= 6 && height >= 150));

        int[] years = {1900, 2000, 2024, 2026};
        for (int y : years) {
            boolean leap = (y % 4 == 0 && y % 100 != 0) || (y % 400 == 0);
            System.out.println("[Q5-③] " + y + "년 윤년? " + leap);
        }

        double ave = 3.5;
        int toefl = 550;
        System.out.println("[Q5-④] " + (ave >= 3.0 && (toefl >= 300 || toefl <= 700)));
    }
}
