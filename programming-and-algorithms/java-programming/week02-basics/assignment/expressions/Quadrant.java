import java.util.Scanner;

/**
 * [2강 과제] 수식 - 4번
 * 조건 연산자 ?: 만을 이용하여 2차원 공간의 x좌표와 y좌표를 입력받아서
 * 그 좌표가 속하는 사분면을 출력하는 프로그램을 작성하라.
 *
 * | 좌표의 부호     | 사분면 |
 * |-----------------|--------|
 * | x > 0, y > 0    | 1      |
 * | x < 0, y > 0    | 2      |
 * | x < 0, y < 0    | 3      |
 * | x > 0, y < 0    | 4      |
 *
 * 실행 예
 *  x좌표를 입력하시오: 2
 *  y좌표를 입력하시오: 4
 *  좌표는 1사분면입니다.
 *
 * 풀이: 조건 연산자를 중첩해서 사용
 *  - 먼저 x 의 부호로 (1, 4) 그룹과 (2, 3) 그룹을 나누고
 *  - 각 그룹 안에서 y 의 부호로 사분면을 결정한다.
 *  - 조건 연산자는 오른쪽 → 왼쪽으로 결합하므로 괄호 없이도 동작하지만, 가독성을 위해 괄호를 친다.
 *
 * 참고) x 나 y 가 0 이면 축 위의 점이라 어느 사분면에도 속하지 않는다.
 *       문제에서 요구하지 않았으므로 이 풀이에서는 0 을 음수 쪽으로 처리한다.
 *       (조건문을 배운 뒤에는 축 위의 점을 따로 처리할 수 있다.)
 */
public class Quadrant {
    public static void main(String[] args) {
        Scanner sc = new Scanner(System.in);
        System.out.print("x좌표를 입력하시오: ");
        int x = sc.nextInt();
        System.out.print("y좌표를 입력하시오: ");
        int y = sc.nextInt();
        sc.close();

        int quadrant = (x > 0) ? ((y > 0) ? 1 : 4)
                               : ((y > 0) ? 2 : 3);

        System.out.println("좌표는 " + quadrant + "사분면입니다.");
    }
}
