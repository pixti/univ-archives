/**
 * [2-7 수식3] [실습] 증감 연산자 실습하기
 *
 * | 연산 | 의미                     |
 * |------|--------------------------|
 * | ++a  | a 를 증가시킨 후 a 를 사용 (전위) |
 * | a++  | a 를 사용한 후 a 를 증가 (후위)   |
 * | --a  | a 를 감소시킨 후 a 를 사용 (전위) |
 * | a--  | a 를 사용한 후 a 를 감소 (후위)   |
 *
 * 예시 (슬라이드 8)
 *   int a = 3, b = 0, c;
 *   c = ++a + b;   →  a = a + 1;  c = a + b;
 *   c = a++ + b;   →  c = a + b;  a = a + 1;
 *   ++a;           →  단독으로 쓰일 경우 결과는 a++ 와 같다.
 *   감소 연산자(--)도 같은 방식.
 *
 * 📝 필기 (퀴즈 때 질문했던 내용)
 *  Q. z = ++x + ++y; 에서 전위 증가 연산자는 y 다음 x 순서인가, x 다음 y 순서인가?
 *  A. x 가 먼저 처리되고 그다음 y 가 처리된다.
 *     자바는 연산자 우선순위와 별개로 "피연산자는 무조건 왼쪽에서 오른쪽(Left-to-Right) 순서로 평가"한다.
 *     1단계) 왼쪽 항 ++x 실행 → x 증가 (왼쪽 값 확정)
 *     2단계) 오른쪽 항 ++y 실행 → y 증가 (오른쪽 값 확정)
 *     3단계) 덧셈
 *     4단계) 우선순위가 가장 낮은 대입(=) 이 마지막에 실행
 *     참고: C/C++ 은 컴파일러 최적화 방식에 따라 오른쪽 항을 먼저 계산하기도 하지만,
 *           자바는 어떤 컴퓨터에서 실행해도 결과가 똑같도록 '왼쪽부터 순서대로'를 언어 스펙으로 강제한다.
 *
 * 실행 결과
 *  a=4 b=6 c=5 d=2    ← d = 3 + 5 - 6 (사용 후 증감)
 *  a=4 b=6 c=5 d=5    ← d = 4 + 6 - 5 (증감 후 사용)
 *  a=4 b=6 c=5 d=4    ← d = 4 + 5 - 5
 */
public class IncDecOperation {
    public static void main(String[] args) {
        int a, b, c, d;

        a = 3; b = 5; c = 6;
        d = a++ + b++ - c--;
        // 슬라이드는 "a=" + a + "b=" + ... 로 공백 없이 붙어서 출력됨 → 보기 좋게 공백 추가
        System.out.println("a=" + a + " b=" + b + " c=" + c + " d=" + d);

        a = 3; b = 5; c = 6;
        d = ++a + ++b - --c;
        System.out.println("a=" + a + " b=" + b + " c=" + c + " d=" + d);

        a = 3; b = 5; c = 6;
        d = ++a + b++ - --c;
        System.out.println("a=" + a + " b=" + b + " c=" + c + " d=" + d);
    }
}
